#!/usr/bin/env python3
"""Give Windows-only game XMLs a Linux block built from LinuxGSM.

Usage:
  python3 tools/lgsm_xml/add_linux_blocks.py LINUXGSM_DIR CONFIG_DIR

The panel copies every root-level setting into each OS block unless that block
has its own. In a Windows-only file the root settings are Windows settings
(paths, batch pre_start, config edits), so before a Linux block is added they
are moved into the <windows> block. Windows sees the same merged config as
before; check_merged.php proves that.
"""
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import generate  # noqa: E402

# Our game_key -> LinuxGSM short name.
GAMES = {
    "conanexiles": "ce",
    "colonysurvival": "col",
    "dayz": "dayz",
    "eco": "eco",
    "wurmu": "wurm",
}

# Root settings that describe the game, not one OS. They stay at the root.
GAME_LEVEL = {"game_key", "protocol", "lgsl_query_name", "gameq_query_name", "installer",
              "game_name", "os", "max_user_amount", "mods"}


def move_root_settings_to_windows(root):
    windows = root.find("os/windows")
    for child in list(root):
        if not isinstance(child.tag, str) or child.tag in GAME_LEVEL:
            continue
        root.remove(child)
        if windows.find(child.tag) is None:
            windows.append(child)
        # If Windows already had its own copy, the root one was never used.


def linux_element(key, short_name, lgsm_dir):
    game = generate.game_from_linuxgsm(short_name, key, "", lgsm_dir, {})
    lines = generate.platform_xml("linux", game["linux"], indent="")
    return ET.fromstring("\n".join(lines)), game["notes"]


def main():
    lgsm_dir, config_dir = Path(sys.argv[1]), Path(sys.argv[2])
    for key, short_name in GAMES.items():
        path = config_dir / f"{key}.xml"
        parser = ET.XMLParser(target=ET.TreeBuilder(insert_comments=True))
        tree = ET.parse(path, parser)
        root = tree.getroot()
        if root.find("os/linux") is not None:
            print(f"{key}.xml already has a Linux block; skipped")
            continue
        move_root_settings_to_windows(root)
        linux, notes = linux_element(key, short_name, lgsm_dir)
        root.find("os").append(linux)
        for note in notes:
            root.insert(0, ET.Comment(f" Linux block: {note} "))
        root.insert(0, ET.Comment(f" Linux block generated by tools/lgsm_xml from LinuxGSM {short_name}server. "))
        ET.indent(tree, space="  ")
        tree.write(path, encoding="utf-8", xml_declaration=True)
        print(f"{key}.xml: root settings moved into <windows>; Linux block added from LinuxGSM {short_name}server")


if __name__ == "__main__":
    main()
